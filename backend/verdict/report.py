"""Report assembly, saving, and extract-only fallbacks."""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from .extract import truncate
from .models import SearchResult, Source, SourceSummary
from .product import same_page


def _timestamp() -> datetime:
    return datetime.now().astimezone()


def _stamp(moment: datetime | None = None) -> str:
    return (moment or _timestamp()).strftime("%Y-%m-%d %H:%M %Z")


def slugify(value: str, max_length: int = 60) -> str:
    slug = re.sub(r"[^\w\s-]", "", value.lower(), flags=re.UNICODE).strip()
    slug = re.sub(r"[\s_-]+", "-", slug).strip("-")
    return slug[:max_length].strip("-") or "report"


def sources_markdown(summaries: list[SourceSummary]) -> str:
    lines = ["## Sources", ""]
    for index, summary in enumerate(summaries, 1):
        title = " ".join((summary.title or summary.url).split())
        title = title.replace("[", r"\[").replace("]", r"\]")
        line = f"{index}. [{title}](<{summary.url}>)"
        if summary.error:
            line += f" — _partial: {summary.error}_"
        lines.append(line)
    return "\n".join(lines)


def product_sources_markdown(
    product: str,
    summaries: list[SourceSummary],
    product_url: str = "",
) -> str:
    title = " ".join(str(product or "").split()) or "Product"
    lines = ["## Sources", "", f"Research for: **{title}**", ""]
    for index, summary in enumerate(summaries, 1):
        label = " ".join((summary.title or summary.url).split())
        label = label.replace("[", r"\[").replace("]", r"\]")
        line = f"{index}. [{label}](<{summary.url}>)"
        if product_url and same_page(summary.url, product_url):
            line += " — _primary product page_"
        if summary.error:
            line += f" — _partial: {summary.error}_"
        lines.append(line)
    return "\n".join(lines)


def report_footer(models: list[str], moment: datetime | None = None) -> str:
    ai = ", ".join(sorted(set(models))) if models else "disabled (extract-only)"
    return (
        "---\n"
        f"*Generated by Verdict on {_stamp(moment)} · AI: {ai} · Scraping: Oxylabs.*\n"
        "*AI summaries can be wrong. Verify critical facts against the linked sources.*"
    )


def save_report(
    markdown: str,
    report_dir: Path,
    topic: str,
    moment: datetime | None = None,
) -> Path:
    moment = moment or _timestamp()
    report_dir.mkdir(parents=True, exist_ok=True)
    filename = f"{moment.strftime('%Y%m%d-%H%M%S')}-{slugify(topic)}.md"
    path = report_dir / filename
    path.write_text(markdown.rstrip() + "\n", encoding="utf-8")
    return path


def _source_heading(source: Source, index: int) -> str:
    title = " ".join((source.title or source.url).split())
    return f"## [{index}] {title}"


def build_raw_report(
    topic: str,
    sources: list[Source],
    *,
    results: list[SearchResult] | None = None,
    note: str = "AI summary disabled or unavailable.",
) -> str:
    """Deterministic report used when summarization is off or fails."""

    lines = [
        f"# Extracted content: {topic or 'Web research'}",
        "",
        f"_{note} · Generated {_stamp()} · Scraped with Oxylabs._",
        "",
    ]

    if results:
        lines.extend(["## Search results", ""])
        for index, result in enumerate(results, 1):
            snippet = " ".join(result.snippet.split())
            suffix = f" — {snippet}" if snippet else ""
            lines.append(f"{index}. [{result.title or result.url}]({result.url}){suffix}")
        lines.append("")

    if not sources:
        lines.append("_No pages could be scraped._")
        return "\n".join(lines)

    for index, source in enumerate(sources, 1):
        lines.append(_source_heading(source, index))
        details = [f"[{source.url}]({source.url})"]
        if source.site_name:
            details.append(source.site_name)
        if source.author:
            details.append(f"by {source.author}")
        if source.published:
            details.append(source.published)
        if source.error:
            details.append(f"partial: {source.error}")
        lines.append(" · ".join(details))
        lines.append("")
        lines.append(truncate(source.text, 8_000).strip() or "_No readable text._")
        lines.append("")

    return "\n".join(lines).rstrip()
