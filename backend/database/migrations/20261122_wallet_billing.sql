CREATE OR REPLACE FUNCTION verdict_grant_credits(
    p_user_id UUID,
    p_amount INTEGER,
    p_kind TEXT,
    p_type TEXT,
    p_reference TEXT DEFAULT NULL,
    p_reset BOOLEAN DEFAULT FALSE,
    p_amount_cents INTEGER DEFAULT NULL,
    p_description TEXT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
    v_sub INTEGER;
    v_pur INTEGER;
    v_before INTEGER;
    v_after INTEGER;
    v_reference_type TEXT;
BEGIN
    IF p_amount <= 0 OR p_kind NOT IN ('purchased', 'subscription') THEN
        RAISE EXCEPTION 'invalid credit grant';
    END IF;

    INSERT INTO credit_wallets (user_id) VALUES (p_user_id) ON CONFLICT (user_id) DO NOTHING;
    SELECT subscription_credits, purchased_credits INTO v_sub, v_pur
      FROM credit_wallets WHERE user_id = p_user_id FOR UPDATE;

    IF p_reference IS NOT NULL THEN
        v_reference_type := CASE WHEN p_kind = 'subscription' THEN 'subscription_grant' ELSE p_type END;
        IF EXISTS (
            SELECT 1 FROM credit_transactions
             WHERE user_id = p_user_id AND type = v_reference_type AND payment_reference = p_reference
        ) THEN
            RETURN jsonb_build_object('granted', FALSE, 'reason', 'duplicate');
        END IF;
    END IF;

    v_before := v_sub + v_pur;
    IF p_reset AND p_kind = 'subscription' THEN
        v_sub := p_amount;
    ELSIF p_kind = 'subscription' THEN
        v_sub := v_sub + p_amount;
    ELSE
        v_pur := v_pur + p_amount;
    END IF;

    UPDATE credit_wallets
       SET subscription_credits = v_sub, purchased_credits = v_pur, updated_at = now()
     WHERE user_id = p_user_id;
    v_after := v_sub + v_pur;

    INSERT INTO credit_transactions (
        user_id, type, amount, status, payment_reference, amount_cents,
        currency, description, reference_type, balance_before, balance_after
    ) VALUES (
        p_user_id, p_type, p_amount, 'completed', p_reference, p_amount_cents,
        'usd', p_description, v_reference_type, v_before, v_after
    );

    RETURN jsonb_build_object(
        'granted', TRUE, 'balance_before', v_before, 'balance_after', v_after,
        'subscription_credits', v_sub, 'purchased_credits', v_pur
    );
END;
$$;

CREATE OR REPLACE FUNCTION verdict_claim_webhook_event(
    p_event_id TEXT,
    p_type TEXT DEFAULT ''
) RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO stripe_webhook_events (id, type) VALUES (p_event_id, p_type)
    ON CONFLICT (id) DO NOTHING;
    RETURN FOUND;
END;
$$;

REVOKE ALL ON FUNCTION verdict_grant_credits(UUID, INTEGER, TEXT, TEXT, TEXT, BOOLEAN, INTEGER, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION verdict_claim_webhook_event(TEXT, TEXT) FROM PUBLIC;
